//! dgVoodoo2 DirectDraw and Direct3D Immediate Mode wrapper for native Windows.
//!
//! Colin McRae Rally (1998) draws through DirectDraw and `IDirect3D2`. Under
//! Wine/Proton, Wine's own `ddraw` (`wined3d`) implements those interfaces; on
//! Windows 10 and 11, Microsoft's `ddraw.dll` lacks the legacy Immediate Mode
//! features and high-resolution surface support the game and F10 need, so the
//! game exits during DirectDraw set-up without a wrapper (`docs/RUNTIME_NOTES.md`,
//! 2026-11-03).
//!
//! When running on native Windows (`!wine`), the launcher installs the bundled
//! `DDraw.dll` and `D3DImm.dll` (dgVoodoo2 2.87.6, from `dgvoodoo/` next to
//! `CMRLauncher.exe`) into the runtime folder through [`rea_launcher::ledger::Ledger`]
//! and writes `dgVoodoo.conf`. Under Wine, it takes them out so Wine uses its
//! own `ddraw`.

use std::fs;
use std::path::Path;

use rea_launcher::fsx;
use rea_launcher::ledger::{Ledger, Outcome};

use crate::config::{Settings, TextureFilter};

pub const DLLS: [&str; 2] = ["DDraw.dll", "D3DImm.dll"];
pub const CONF: &str = "dgVoodoo.conf";
pub const OWNERSHIP_FILE: &str = ".cmr-launcher-components";

/// Generates `dgVoodoo.conf` from `settings` (verified on Windows 11 in
/// `docs/RUNTIME_NOTES.md`, 2026-11-03).
pub fn conf(settings: &Settings) -> String {
    let filtering = match settings.texture_filter {
        Some(TextureFilter::Smooth) => "16",
        _ => "appdriven",
    };
    let vsync = if settings.vsync == Some(true) {
        "true"
    } else {
        "false"
    };
    format!(
        "; Generated by CMRLauncher — rewritten on each launch.\n\
         [General]\n\
         OutputAPI                           = bestavailable\n\
         FullScreenMode                      = true\n\
         ScalingMode                         = stretched_ar\n\
         CaptureMouse                        = false\n\n\
         [GeneralExt]\n\
         FullscreenAttributes                = fake\n\n\
         [DirectX]\n\
         VideoCard                           = internal3D\n\
         VRAM                                = 256\n\
         Mipmapping                          = appdriven\n\
         Filtering                           = {filtering}\n\
         KeepFilterIfPointSampled            = true\n\
         ForceVerticalSync                   = {vsync}\n\
         dgVoodooWatermark                   = false\n"
    )
}

fn owned_conf(bytes: &[u8]) -> bool {
    bytes.starts_with(b"; Generated by CMRLauncher")
        || bytes.starts_with(b"[General]\nOutputAPI")
        || bytes.starts_with(b"[General]\r\nOutputAPI")
}

/// Installs `DDraw.dll`, `D3DImm.dll` and `dgVoodoo.conf` into `runtime` on
/// native Windows (`!wine`), or removes launcher-owned copies under Wine.
/// Returns a `launcher.log` line when anything is worth noting.
pub fn sync(
    game: &Path,
    runtime: &Path,
    bundled_dir: &Path,
    settings: &Settings,
    wine: bool,
) -> Result<Option<String>, String> {
    let mut ledger = Ledger::load(game, runtime, OWNERSHIP_FILE);
    let conf_path = runtime.join(CONF);
    if wine {
        for name in DLLS {
            let bundled = fs::read(bundled_dir.join(name)).ok();
            let known: &[&[u8]] = match bundled.as_deref() {
                Some(b) => &[b],
                None => &[],
            };
            if ledger
                .take_out(name, known)
                .map_err(|e| format!("cannot remove {name} from {}: {e}", runtime.display()))?
                == Outcome::NotOurs
            {
                return Err(format!(
                    "runtime {name} is not launcher-owned; refusing to remove {}",
                    runtime.join(name).display()
                ));
            }
        }
        if fs::read(&conf_path).is_ok_and(|b| owned_conf(&b)) {
            let _ = fsx::remove(&conf_path);
        }
        return Ok(None);
    }

    if !DLLS.iter().all(|name| bundled_dir.join(name).is_file()) {
        return Ok(Some(format!(
            "warning: dgVoodoo2 not found in {}; DirectDraw on Windows needs DDraw.dll and D3DImm.dll",
            bundled_dir.display()
        )));
    }

    for name in DLLS {
        let src = bundled_dir.join(name);
        let bytes = fs::read(&src).map_err(|e| format!("cannot read {}: {e}", src.display()))?;
        if ledger
            .install(name, &bytes, &[&bytes])
            .map_err(|e| format!("cannot install {name} into {}: {e}", runtime.display()))?
            == Outcome::NotOurs
        {
            return Err(format!(
                "runtime {name} is not launcher-owned; refusing to replace {}",
                runtime.join(name).display()
            ));
        }
    }
    // A dgVoodoo.conf the player wrote stays as it is; ours is rewritten
    // from the settings on every start (issue #5: a hand-tuned file came
    // back replaced).
    if fs::read(&conf_path).is_ok_and(|b| !owned_conf(&b)) {
        return Ok(Some(
            "Windows: dgVoodoo2 2.87.6 (DDraw.dll, D3DImm.dll) ready; your dgVoodoo.conf is used as it is"
                .into(),
        ));
    }
    fsx::write_atomic(&conf_path, conf(settings))
        .map_err(|e| format!("cannot write {}: {e}", conf_path.display()))?;
    Ok(Some(
        "Windows: dgVoodoo2 2.87.6 (DDraw.dll, D3DImm.dll, dgVoodoo.conf) ready".into(),
    ))
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    fn temp(name: &str) -> PathBuf {
        let p =
            std::env::temp_dir().join(format!("cmr-dgvoodoo-test-{}-{name}", std::process::id()));
        let _ = fs::remove_dir_all(&p);
        fs::create_dir_all(&p).unwrap();
        p
    }

    #[test]
    fn conf_follows_texture_filter_and_vsync() {
        let base = conf(&Settings::default());
        assert!(base.contains("FullscreenAttributes                = fake"));
        assert!(base.contains("Filtering                           = appdriven"));
        assert!(base.contains("ForceVerticalSync                   = false"));
        assert!(base.contains("dgVoodooWatermark                   = false"));

        let smooth = conf(&Settings {
            texture_filter: Some(TextureFilter::Smooth),
            vsync: Some(true),
            ..Settings::default()
        });
        assert!(smooth.contains("Filtering                           = 16"));
        assert!(smooth.contains("ForceVerticalSync                   = true"));
    }

    #[test]
    fn installs_on_windows_and_takes_out_on_wine() {
        let root = temp("lifecycle");
        let game = root.join("game");
        let rt = root.join("rt");
        let bundled = root.join("dgvoodoo");
        fs::create_dir_all(&game).unwrap();
        fs::create_dir_all(&rt).unwrap();
        fs::create_dir_all(&bundled).unwrap();
        for name in DLLS {
            fs::write(bundled.join(name), format!("bundled {name}")).unwrap();
        }

        let msg = sync(&game, &rt, &bundled, &Settings::default(), false)
            .unwrap()
            .unwrap();
        assert!(msg.contains("dgVoodoo2"), "{msg}");
        for name in DLLS {
            assert_eq!(
                fs::read(rt.join(name)).unwrap(),
                format!("bundled {name}").as_bytes()
            );
        }
        assert!(rt.join(CONF).is_file());

        // Switching to Wine removes the wrapper DLLs and generated config.
        assert_eq!(
            sync(&game, &rt, &bundled, &Settings::default(), true).unwrap(),
            None
        );
        for name in DLLS {
            assert!(!rt.join(name).exists(), "{name} should be removed");
        }
        assert!(!rt.join(CONF).exists());
        fs::remove_dir_all(root).unwrap();
    }

    #[test]
    fn a_players_own_conf_is_kept() {
        // Issue #5: a hand-tuned dgVoodoo.conf (Filtering = 16) came back
        // replaced by the generated one.
        let root = temp("own-conf");
        let game = root.join("game");
        let rt = root.join("rt");
        let bundled = root.join("dgvoodoo");
        for d in [&game, &rt, &bundled] {
            fs::create_dir_all(d).unwrap();
        }
        for name in DLLS {
            fs::write(bundled.join(name), format!("bundled {name}")).unwrap();
        }
        let own = "[DirectX]\nFiltering = 16\n";
        fs::write(rt.join(CONF), own).unwrap();
        let msg = sync(&game, &rt, &bundled, &Settings::default(), false)
            .unwrap()
            .unwrap();
        assert_eq!(fs::read_to_string(rt.join(CONF)).unwrap(), own);
        assert!(msg.contains("your dgVoodoo.conf"), "{msg}");
        // Under Wine it stays too.
        sync(&game, &rt, &bundled, &Settings::default(), true).unwrap();
        assert_eq!(fs::read_to_string(rt.join(CONF)).unwrap(), own);
        fs::remove_dir_all(root).unwrap();
    }

    #[test]
    fn refuses_unowned_dll_in_runtime() {
        let root = temp("conflict");
        let game = root.join("game");
        let rt = root.join("rt");
        let bundled = root.join("dgvoodoo");
        fs::create_dir_all(&game).unwrap();
        fs::create_dir_all(&rt).unwrap();
        fs::create_dir_all(&bundled).unwrap();
        for name in DLLS {
            fs::write(bundled.join(name), format!("bundled {name}")).unwrap();
        }
        fs::write(rt.join("DDraw.dll"), b"custom wrapper").unwrap();

        let err = sync(&game, &rt, &bundled, &Settings::default(), false).unwrap_err();
        assert!(err.contains("not launcher-owned"), "{err}");
        assert_eq!(fs::read(rt.join("DDraw.dll")).unwrap(), b"custom wrapper");
        fs::remove_dir_all(root).unwrap();
    }
}
